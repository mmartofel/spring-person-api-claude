CREATE TABLE task (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title          VARCHAR(120)             NOT NULL,
    description    VARCHAR(2000),
    priority       VARCHAR(16)              NOT NULL DEFAULT 'MEDIUM',
    estimate_hours NUMERIC(4, 1),
    done           BOOLEAN                  NOT NULL DEFAULT FALSE,
    due_date       DATE,
    assignee_id    BIGINT,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    version        BIGINT                   NOT NULL,
    CONSTRAINT pk_task PRIMARY KEY (id),
    CONSTRAINT fk_task_assignee FOREIGN KEY (assignee_id) REFERENCES person (id) ON DELETE RESTRICT,
    CONSTRAINT ck_task_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_task_estimate_hours CHECK (estimate_hours BETWEEN 0.5 AND 999 AND estimate_hours % 0.5 = 0)
);

CREATE INDEX ix_task_assignee_id ON task (assignee_id);
